import assert from 'node:assert/strict';
import { intakeDraftReady, intakeChange, intakeChangeText, lastSavedIntakeChange, stampIntakeChange } from './mobile-intake';
import { defaultDoorLine, normalizeDoorLineInput } from './door-line-contract';
import { duplicateDoorLine } from './door-line-editor-state';
import type { NativeDoorLine, NativeJobAggregate } from './job-intake-types';
const id = '11111111-1111-4111-8111-111111111111';
const a = { ...defaultDoorLine(), lineId: 'a', lineIndex: 1, lineStatus: 'Active', qty: 2, individualDoorIds: ['A', 'B', 'Retained'] } as NativeDoorLine;
const b = { ...a, lineId: 'b', lineIndex: 2, qty: 1 };
const input = [a, b]; const before = JSON.stringify(input);
const stamped = stampIntakeChange([{ ...a, qty: 3 }, b], { lineId: 'a', kind: 'quantity', before: 2, quantity: 3 }, 2, id);
assert.equal(JSON.stringify(input), before);
assert.deepEqual(stamped.map(line => line.lineId), ['a', 'b']);
assert.deepEqual(stamped[0].individualDoorIds, ['A', 'B', 'Retained']);
const receipt = intakeChange(JSON.stringify(stamped[0].intakeChange))!;
assert.equal(intakeChangeText(receipt), 'Quantity updated: 2 → 3');
assert.equal(intakeChange('{broken'), undefined);
assert.equal(intakeChange({ ...receipt, quantity: 0 }), undefined);
assert.equal(intakeChange({ ...receipt, before: null }), undefined);
assert.equal(intakeChange({ ...receipt, revision: -1 }), undefined);
const job = { revision: 2, lines: stamped } as NativeJobAggregate;
assert.equal(lastSavedIntakeChange(job)?.lineId, 'a');
assert.equal(lastSavedIntakeChange({ ...job, revision: 1 }), null, 'pending/future marker cannot be treated as saved');
assert.equal(lastSavedIntakeChange({ ...job, lines: input }), null, 'pre-save server snapshot has no success');
assert.equal(lastSavedIntakeChange({ ...job, lines: [{ ...stamped[0], qty: 4 } as NativeDoorLine] }), null, 'outdated quantity receipt is hidden');
assert.equal(lastSavedIntakeChange({ ...job, lines: [{ ...stamped[0], lineStatus: 'Archived' } as NativeDoorLine] }), null);
assert.deepEqual(lastSavedIntakeChange(JSON.parse(JSON.stringify(job))), lastSavedIntakeChange(job), 'receipt survives reload');
assert.equal(duplicateDoorLine(stamped[0], 'new', 3).intakeChange, undefined, 'a duplicate must not impersonate an earlier successful save');
const normalized = normalizeDoorLineInput(stamped[0]);
assert.equal(normalized.ok, true);
if (normalized.ok) assert.deepEqual(normalized.value.intakeChange, receipt, 'normalization and recalculation retain the receipt');
assert.throws(() => stampIntakeChange(input, { lineId: 'missing', kind: 'added', before: null, quantity: 1 }, 2, id));
console.log('Mobile intake receipt persistence, acknowledgement/revision gates, ordering, quantities, duplicate safety and individual IDs passed.');

const resetDraft = defaultDoorLine();
const resetSnapshot = JSON.stringify(resetDraft);
const submittedDraft = { ...resetDraft, doorId: 'First opening' };
const submittedSnapshot = JSON.stringify(submittedDraft);
assert.equal(intakeDraftReady(resetDraft, resetSnapshot), false, 'a fresh unchanged form does not express a new opening');
assert.equal(intakeDraftReady(submittedDraft, resetSnapshot), true, 'entering an opening enables its first save');
assert.equal(intakeDraftReady(submittedDraft, resetSnapshot, submittedSnapshot), false, 'a delayed click with the completed draft is rejected even before React commits the reset');
assert.equal(intakeDraftReady(resetDraft, resetSnapshot, submittedSnapshot), false, 'a queued click on the reset defaults cannot create a second line');
assert.equal(intakeDraftReady({ ...resetDraft, doorId: 'Second opening' }, resetSnapshot, submittedSnapshot), true, 'the next distinct draft is permitted');
assert.equal(intakeDraftReady(resetDraft, resetSnapshot, submittedSnapshot, true), true, 'explicit updates to an existing line remain allowed');
console.log('Completed-draft and reset-draft resubmission guards passed.');

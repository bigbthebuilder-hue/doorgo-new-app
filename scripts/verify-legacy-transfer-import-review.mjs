import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(path, 'utf8');
const page = read('app/jobs/import/page.tsx');
const jobs = read('app/jobs/page.tsx');
const jobsWorkspace = read('components/jobs/JobsWorkspace.tsx');
const review = read('components/jobs/LegacyJobImportReview.tsx');
const importShell = read('components/jobs/LegacyJobImportShell.tsx');
const form = read('components/jobs/JobHeaderForm.tsx');
const action = read('lib/jobs/job-intake-actions.ts');
const service = read('lib/jobs/job-intake-service.ts');
const hosted = read('lib/jobs/hosted-job-intake-repository.ts');
const local = read('lib/jobs/local-job-intake-repository.ts');
const fixture = read('tests/fixtures/legacy-transfer-job-0065.json');
const mapping = read('lib/jobs/legacy-transfer-mapping.ts');
const presentation = read('lib/jobs/legacy-transfer-review-presentation.ts');
const lines = read('components/jobs/DoorLineWorkspace.tsx');
const glassBuilder = read('components/jobs/GlassUnitBuilder.tsx');
const browserTest = read('tests/legacy-transfer-import-browser/legacy-transfer-review.spec.tsx');
const glassBrowserTest = read('tests/legacy-transfer-import-browser/imported-glass-builder.spec.tsx');

assert.match(jobs, /<JobsWorkspace/);
assert.match(jobsWorkspace, /href="\/jobs\/import"[^>]*>Import Legacy Job/);
assert.match(page, /canUse\(access, 'jobs'\)[\s\S]*redirect\('\/account'\)/);
assert.doesNotMatch(page, /<AppShell/, 'state-aware shell ownership must remain with the client import flow');
assert.match(page, /inAppShell navigation=\{buildProtectedAppNavigation\(access\)\}/);
assert.match(review, /review[\s\S]*<LegacyJobImportShell editorActive/);
assert.match(importShell, /editorActive \? 'workspace' : 'main'/);
assert.match(importShell, /hasBottomBar=\{editorActive\}[\s\S]*hasTopBar=\{editorActive\}/);
assert.match(review, /legacyTransferFilePreflight\(file\)[\s\S]*await file\.text\(\)/, 'file size/type must be checked before parsing');
assert.match(review, /accept="application\/json,\.json"/);
assert.match(form, /No native job, UUID, revision, or new DoorGo reference exists/);
assert.match(form, /Save as Native Job/);
assert.match(form, /jobSaveConfirmation\(saved\)/, 'save confirmation must use the authoritative saved aggregate identifier');
assert.doesNotMatch(form, /`\$\{saved\.doorGoReference\} saved\.`/, 'nullable DoorGo reference must not drive the confirmation');
assert.match(form, /router\.replace\(`\/jobs\/\$\{saved\.internalJobId\}\/edit`\)/, 'successful Revision 1 creation must navigate to the normal editor');
assert.match(form, /disabled=\{isPending \|\| Boolean\(transferReview && unresolvedTransferBlockers/, 'immutable blockers must disable Save');
assert.match(form, /The legacy source must be archived manually/);
assert.match(form, /primaryIdentifier\.value/);
assert.doesNotMatch(form, /label="Legacy Job ID"|id="legacyJobId"/, 'no second legacy identifier input is allowed');
assert.match(action, /inspectLegacyTransferAction[\s\S]*mapLegacyTransferToUnsavedEditor/);
assert.match(action, /createTransferredJobAction[\s\S]*createTransferredJobWithAccess/);
assert.doesNotMatch(action.match(/inspectLegacyTransferAction[\s\S]*?\n\}/)?.[0] ?? '', /createJobIntakeRepository|\.create\(|\.rpc\(/, 'inspection and cancellation must not reach persistence');
assert.match(service, /mapLegacyTransferToUnsavedEditor\(request\.rawPayload\)/);
assert.match(service, /transferLineIds\[index\][\s\S]*lineIndex: index \+ 1[\s\S]*lineStatus: 'Active'/);
assert.match(hosted, /async createTransferred[\s\S]*call\('dg_create_transferred_native_job'/);
assert.doesNotMatch(hosted.match(/async createTransferred[\s\S]*?\n    },/)?.[0] ?? '', /dg_create_native_job/);
assert.match(local, /async createTransferred\(\)[\s\S]*local_intake_disabled/, 'local fallback must fail closed');
assert.match(fixture, /"identifier_kind": "legacy_job_id"[\s\S]*"identifier_value": "JOB-0065"/);
assert.match(lines, /key=\{importedLineRenderKey\(line, index\)\}/, 'id-less imported lines need deterministic fallback keys');
assert.doesNotMatch(lines, /key=\{String\(line\.lineId\)\}/, 'undefined line IDs must never be used directly as keys');
assert.doesNotMatch(lines, /key=\{`\$\{entry\.code\}:\$\{entry\.message\}`\}/, 'nested line evidence keys need an occurrence ordinal');
assert.doesNotMatch(glassBuilder, /key=\{issue\.code\}/, 'nested glass evidence must not assume its code is unique');
assert.match(mapping, /function lineEvidencePath[\s\S]*`lines\.\$\{index\}\.\$\{field\}`[\s\S]*uniqueLegacyTransferIssues/, 'exact evidence duplicates must be removed without losing line scope');
assert.match(presentation, /JSON\.stringify\(\[group, issue\.code, issue\.path, issue\.message, occurrence\]\)/, 'evidence keys must include stable content and occurrence');
assert.match(browserTest, /consoleErrors[\s\S]*same key[\s\S]*toEqual\(\[\]\)/, 'focused rendering must assert that React reports no duplicate keys');
assert.match(lines, /editingIndex !== null[\s\S]*replaceDoorLineAtIndex\(lines, editingIndex, saved\)/, 'id-less imported lines must update by their local editor position');
assert.match(glassBrowserTest, /Status: Complete[\s\S]*attention-count[\s\S]*toHaveText\('0'\)/, 'completed imported glass must clear attention state');
assert.doesNotMatch(glassBrowserTest, /createTransferredJobAction|\.rpc\(|fetch\(/, 'focused glass rendering must remain local-only');
for (const forbidden of ['dg_production', 'dg_calendar', 'dg_fulfillment', 'dg_document', 'resend', 'send email']) {
  for (const source of [review, action, service]) assert.ok(!source.toLowerCase().includes(forbidden), `import runtime references prohibited boundary: ${forbidden}`);
}

console.log('Legacy transfer import/review static verification passed');
